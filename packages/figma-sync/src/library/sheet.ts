import { nameOf } from '../model.ts';
import type { ComponentFacts, Library, LayerFacts } from './spec.ts';
import type { LayerSpec, StylesSpec } from './runtime.ts';
import { COMPONENTS_PAGE } from './styles.ts';

const v = (path: string) => `\`${nameOf(path)}\``;

const SIDES: readonly [string, string][] = [
  ['paddingTop', 'top'],
  ['paddingRight', 'right'],
  ['paddingBottom', 'bottom'],
  ['paddingLeft', 'left'],
];

/** One layer's bindings as a sentence, in Figma's names. */
export function describeLayer(layer: LayerSpec): string {
  const out: string[] = [];
  const b = layer.bound;
  const pads = SIDES.filter(([f]) => b[f] !== undefined);
  if (pads.length > 0) {
    const values = pads.map(([f]) => b[f]);
    out.push(
      pads.length === 4 && values.every((x) => x === values[0])
        ? `padding ${v(String(values[0]))}`
        : `padding ${pads.map(([f, side]) => `${side} ${v(String(b[f]))}`).join(', ')}`,
    );
  }
  if (b.itemSpacing) out.push(`gap ${v(b.itemSpacing)}`);
  if (b.topLeftRadius) out.push(`radius ${v(b.topLeftRadius)}`);
  if (b.width) out.push(`width ${v(b.width)}`);
  if (b.height) out.push(`height ${v(b.height)}`);
  if (layer.fill !== undefined)
    out.push(layer.fill === '' ? 'no fill' : `fill ${v(layer.fill)}`);
  if (layer.stroke !== undefined)
    out.push(
      `inside stroke ${v(layer.stroke)}${b.strokeWeight ? ` at ${v(b.strokeWeight)}` : ''}`,
    );
  if (layer.effect) out.push(`effect style ${v(layer.effect)}`);
  if (layer.color) out.push(`text and icons ${v(layer.color)}`);
  const t = layer.typography;
  if (t?.style) out.push(`text style ${v(t.style)}`);
  else if (t) {
    const bound = (
      ['fontFamily', 'fontSize', 'fontWeight', 'letterSpacing'] as const
    )
      .filter((f) => t[f] !== undefined)
      .map((f) => `${f} ${v(String(t[f]))}`);
    out.push(
      `text with ${[...bound, ...(t.lineHeight !== undefined ? [`line height ${String(t.lineHeight)}%`] : [])].join(', ')}`,
    );
  }
  return out.join('; ');
}

const raw = (layer: LayerFacts) =>
  Object.entries(layer.raw)
    .map(([k, value]) =>
      // Case is part of a Figma text style, so setting it on a layer detaches the style.
      k === 'text-transform'
        ? `text-transform: ${value} in code only, since it would detach the text style`
        : `${k}: ${value}`,
    )
    .join('; ');

function component(c: ComponentFacts): string {
  const s = c.spec;
  const lines = [
    `## ${s.name}`,
    '',
    `A ${s.axes.length > 0 ? 'component set' : 'component'} named \`${s.name}\`, in a section named ${s.name}. Its description: "${s.description}"`,
    '',
  ];
  if (s.axes.length > 0)
    lines.push(
      `Variant properties, with the default variant at the top left: ${s.axes
        .map(
          (a) => `\`${a.name}\` (${a.values.join(', ')}; default ${a.default})`,
        )
        .join(', ')}.`,
      '',
    );
  if (s.properties.length > 0)
    lines.push(
      `Component properties: ${s.properties.map((p) => `\`${p.name}\` (${p.type})`).join(', ')}.`,
      '',
    );
  const left = Object.entries(c.leftOut);
  if (left.length > 0)
    lines.push(
      `Left out: ${left.map(([layer, why]) => `\`${layer}\`, ${why[0]?.toLowerCase() ?? ''}${why.slice(1)}`).join(' ')}`,
      '',
    );
  const drawn = Object.entries(c.drawn);
  if (drawn.length > 0)
    lines.push(
      'Drawn in every variant, with no token to bind, so the check leaves them to you:',
      '',
      ...drawn.map(([layer, how]) => `- \`${layer}\`: ${how}`),
      '',
    );
  for (const variant of c.variants) {
    if (s.axes.length > 0) lines.push(`### ${variant.name}`, '');
    for (const layer of variant.layers) {
      const name =
        layer.spec.name === '' ? 'The component' : `\`${layer.spec.name}\``;
      const bindings = describeLayer(layer.spec);
      const r = raw(layer);
      lines.push(
        `- ${name}: ${bindings === '' ? 'no bindings' : bindings}.${r === '' ? '' : ` Layout: ${r}.`}`,
      );
    }
    for (const i of variant.instances)
      lines.push(
        `- An instance of \`${i.component}\`${
          Object.keys(i.variants).length > 0
            ? ` with ${Object.entries(i.variants)
                .map(([k, val]) => `${k}=${val}`)
                .join(', ')}`
            : ''
        }.`,
      );
    lines.push('');
  }
  return lines.join('\n');
}

/** The build sheet: what to build for each component, in Figma's names. */
export function buildSheet(library: Library, styles: StylesSpec): string {
  return [
    '# Fossil component library: build sheet',
    '',
    `Generated by \`pnpm figma:library-spec\`. Build each component in the components file, on its ${COMPONENTS_PAGE} page, in a section named after it, from its JSX and stories, with these names and bindings. \`pnpm figma:library-check\` verifies them.`,
    '',
    'The components file has no variables, styles or icons of its own. Turn the foundations library on in it, then import each from there:',
    '',
    '- variables by key: find each name below with `figma.teamLibrary.getVariablesInLibraryCollectionAsync`, then `figma.variables.importVariableByKeyAsync`;',
    '- text styles, effect styles and icons by the keys the styles script returns, with `figma.importStyleByKeyAsync` and `figma.importComponentByKeyAsync`.',
    '',
    '- Name each layer listed below exactly as written: it is the CSS class, or the state selector, it stands for.',
    '- Bind what each line names, and nothing to a raw value: every fill, stroke, padding, gap and radius uses a variable.',
    '- Text and icons inside a layer take the colour and text style it names, unless a layer inside names its own.',
    '- Layout values are for the agent to follow; the check reads only bindings, names, variants and instances.',
    '',
    `Text styles: ${styles.textStyles.map((t) => `\`${t.name}\``).join(', ')}. Effect styles: ${styles.effectStyles.map((e) => `\`${e.name}\``).join(', ')}. Icons: ${styles.icons.map((i) => `\`${i.name}\``).join(', ')}.`,
    '',
    `Left out of the library: ${Object.entries(library.leftOut)
      .map(([name, why]) => `\`${name}\` (${why})`)
      .join('; ')}`,
    '',
    ...library.components.map(component),
  ].join('\n');
}
